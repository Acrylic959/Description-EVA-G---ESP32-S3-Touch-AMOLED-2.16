#pragma once

#include <Arduino.h>

// ============================================================
// 音频模块 - ES7210 双麦克风音量/节拍检测
// 用于 "听歌哼歌表情同步": 采集环境音量驱动宠物哼唱表情
// ============================================================

// 初始化 ES7210 + I2S (返回 false 表示失败, 功能降级但不影响主功能)
bool audioBegin();

// 采样一帧音频, 更新内部音量/节拍状态 (在 loop 中调用)
float audioSample();

// 当前平滑音量 (0.0 ~ 1.0)
float audioLevel();

// 获取并清除节拍标志 (检测到节拍返回 true)
bool audioBeat();
