def norm(rows):
    out = []
    for r in rows:
        r = r.replace('1', ' ').replace('2', ' ')
        out.append((r + "     ")[:5])
    while len(out) < 7:
        out.append("     ")
    return out[:7]

lines = ["#pragma once",
         "/* 自动生成：sim 用 5x7 点阵字库，覆盖固件里出现的字符 */",
         "static const unsigned char SIM_FONT[128][7] = {"]
for code in range(128):
    ch = chr(code)
    if ch in G:
        rows = norm(G[ch])
    elif ch.lower() in G:
        rows = norm(G[ch.lower()])
    else:
        rows = ["     "] * 7
    b = []
    for r in rows:
        v = 0
        for i, c in enumerate(r):
            if c == '#':
                v |= (1 << (4 - i))
        b.append(v)
    lines.append("  {" + ",".join("0x%02X" % x for x in b) + "},  /* '%s' */" % (ch if 32 <= code < 127 else ' '))
lines.append("};")
